// Regenerates the GarzaHive logo assets from the brand geometry in
// scripts/logo-paths.json (extracted from the parametric brand system in
// brand/ — a bee reduced to hive geometry: a hexagon abdomen sliced into four
// bands plus two hexagon wings in outline). Outputs:
//   - src/client/components/common/garzahive-logo-paths.ts  (data for <GarzaHiveLogo/>)
//   - logo.svg                            (root master, adaptive light/dark)
//   - site/public/logo.svg               (marketing site, dark-only → reversed)
//   - docs/assets/logo.svg + logo-dark.svg  (README <picture> pair)
//   - docs-site/public/logo-light.svg + logo-dark.svg  (Starlight header logo)
//   - docs-site/public/favicon.svg       (adaptive light/dark)
// The dynamic, theme-aware logo is <GarzaHiveLogo/>; these SVGs are for plain
// <img>/README/OG contexts. Run: bun scripts/gen-logo-assets.mjs
// NOTE: this does NOT regenerate the PWA raster icons (favicon/app/apple/
// maskable) under src/client/public/. After changing the logo, also run
// `bun scripts/gen-pwa-icons.mjs` (it rasterizes from the geometry here).
import { readFileSync, writeFileSync } from 'node:fs'

const { icon, wordmark, colors } = JSON.parse(
  readFileSync(new URL('./logo-paths.json', import.meta.url), 'utf8'),
)

const AMBER = colors.amber
const CHARCOAL = colors.charcoal
const WHITE = colors.white

// 1) React component data
writeFileSync(
  new URL('../src/client/components/common/garzahive-logo-paths.ts', import.meta.url),
  `// AUTO-GENERATED by scripts/gen-logo-assets.mjs. Do not edit by hand.
// The GarzaHive mark: a bee reduced to hive geometry. The abdomen is one
// hexagon sliced into four bands (index ${icon.accentBand} is the amber active cell); the
// wings are two flat-top hexagons drawn in outline. Coordinates are centered
// on the mark's origin inside a ${icon.width}x${icon.height} box.
/* eslint-disable */

/** Icon box (the mark is wider than tall — wings extend sideways). */
export const GARZAHIVE_ICON_WIDTH = ${icon.width}
export const GARZAHIVE_ICON_HEIGHT = ${icon.height}

/** Stroke width of the outlined wing hexagons, in icon units. */
export const GARZAHIVE_ICON_WING_STROKE = ${icon.wingStroke}

/** The two wing hexagon outlines (stroke these, never fill). */
export const GARZAHIVE_ICON_WINGS: readonly string[] = [
${icon.wings.map((d) => `  ${JSON.stringify(d)},`).join('\n')}
]

/** The four abdomen bands, top to bottom (fill these). */
export const GARZAHIVE_ICON_BANDS: readonly string[] = [
${icon.bands.map((d) => `  ${JSON.stringify(d)},`).join('\n')}
]

/** Index into GARZAHIVE_ICON_BANDS of the amber "active cell" band. */
export const GARZAHIVE_ICON_ACCENT_BAND = ${icon.accentBand}

/**
 * The GARZAHIVE wordmark (Outfit SemiBold, +170 tracking) outlined to paths.
 * Glyph coordinates are in font units (y-up): render each glyph with
 * \`translate(x,0) scale(s,-s)\` inside a group translated down by capHeight.
 */
export const GARZAHIVE_WORDMARK = {
  width: ${wordmark.width},
  capHeight: ${wordmark.capHeight},
  glyphs: [
${wordmark.glyphs.map((g) => `    { x: ${g.x}, d: ${JSON.stringify(g.d)} },`).join('\n')}
  ],
} as const

/** Brand palette (see brand/README.md). Amber is the only accent. */
export const GARZAHIVE_BRAND_COLORS = {
  amber: ${JSON.stringify(colors.amber)},
  charcoal: ${JSON.stringify(colors.charcoal)},
  white: ${JSON.stringify(colors.white)},
  combWhite: ${JSON.stringify(colors.combWhite)},
  ink: ${JSON.stringify(colors.ink)},
} as const
`,
)

// 2) Static SVG builder ----------------------------------------------------

/** Icon-only mark. `body` paints the bands, `accent` the active cell + wings. */
function iconSvg({ body, accent = AMBER, adaptiveDarkBody = null, label = 'GarzaHive' }) {
  // Bands carry a class so an embedded prefers-color-scheme rule can flip them
  // between charcoal (light) and white (dark) in plain <img>/favicon contexts.
  const style = adaptiveDarkBody
    ? `  <style>.gh-band{fill:${body}}@media (prefers-color-scheme:dark){.gh-band{fill:${adaptiveDarkBody}}}</style>\n`
    : ''
  const wings = icon.wings
    .map(
      (d) =>
        `    <path d="${d}" fill="none" stroke="${accent}" stroke-width="${icon.wingStroke}" stroke-linejoin="round"/>`,
    )
    .join('\n')
  const bands = icon.bands
    .map((d, i) =>
      i === icon.accentBand
        ? `    <path d="${d}" fill="${accent}"/>`
        : adaptiveDarkBody
          ? `    <path class="gh-band" d="${d}"/>`
          : `    <path d="${d}" fill="${body}"/>`,
    )
    .join('\n')
  return `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${icon.width} ${icon.height}" width="${icon.width}" height="${icon.height}" role="img" aria-label="${label}">
${style}  <g transform="translate(${icon.width / 2},${icon.height / 2})">
${wings}
${bands}
  </g>
</svg>
`
}

// 3) Write the static masters ---------------------------------------------

// Root master: adaptive (charcoal bands, white in dark colour schemes).
const adaptive = iconSvg({ body: CHARCOAL, adaptiveDarkBody: WHITE })
writeFileSync(new URL('../logo.svg', import.meta.url), adaptive)

// Marketing site is dark-only → reversed colourway (white bands + amber).
writeFileSync(
  new URL('../site/public/logo.svg', import.meta.url),
  iconSvg({ body: WHITE }),
)

// README <picture> pair (GitHub light/dark).
writeFileSync(
  new URL('../docs/assets/logo.svg', import.meta.url),
  iconSvg({ body: CHARCOAL }),
)
writeFileSync(
  new URL('../docs/assets/logo-dark.svg', import.meta.url),
  iconSvg({ body: WHITE }),
)

// Docs site (Starlight light/dark header logos + adaptive favicon).
writeFileSync(
  new URL('../docs-site/public/logo-light.svg', import.meta.url),
  iconSvg({ body: CHARCOAL }),
)
writeFileSync(
  new URL('../docs-site/public/logo-dark.svg', import.meta.url),
  iconSvg({ body: WHITE }),
)
writeFileSync(
  new URL('../docs-site/public/favicon.svg', import.meta.url),
  adaptive,
)

console.log('regenerated logo assets (component data + static SVG masters)')
